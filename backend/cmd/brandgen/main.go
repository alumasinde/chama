// Command brandgen turns branding.json into compile-time constants.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"
)

type branding struct {
	AppName      string `json:"appName"`
	ShortName    string `json:"shortName"`
	PrimaryColor string `json:"primaryColor"`
	AccentColor  string `json:"accentColor"`
	Currency     string `json:"currency"`
	Locale       string `json:"locale"`
	SupportEmail string `json:"supportEmail"`
}

func main() {
	input := flag.String("file", "../branding.json", "path to branding.json")
	output := flag.String("out", "internal/platform/brand/brand.gen.go", "generated Go file")
	flag.Parse()

	raw, err := os.ReadFile(*input)
	if err != nil {
		fail(err)
	}
	var b branding
	if err := json.Unmarshal(raw, &b); err != nil {
		fail(err)
	}
	if strings.TrimSpace(b.AppName) == "" {
		fail(fmt.Errorf("appName is required in %s", *input))
	}
	if b.ShortName == "" {
		b.ShortName = strings.Fields(b.AppName)[0]
	}

	source := fmt.Sprintf(`// Code generated by cmd/brandgen from branding.json; DO NOT EDIT.
package brand

const (
	AppName      = %q
	ShortName    = %q
	PrimaryColor = %q
	AccentColor  = %q
	Currency     = %q
	Locale       = %q
	SupportEmail = %q
)
`, b.AppName, b.ShortName, b.PrimaryColor, b.AccentColor, b.Currency, b.Locale, b.SupportEmail)

	formatted, err := format.Source([]byte(source))
	if err != nil {
		fail(err)
	}
	if err := os.MkdirAll(filepath.Dir(*output), 0o750); err != nil {
		fail(err)
	}
	if err := os.WriteFile(*output, formatted, 0o600); err != nil {
		fail(err)
	}
	fmt.Printf("brand: %s -> %s\n", b.AppName, *output)
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "brandgen:", err)
	os.Exit(1)
}
